import {
  Bearing,
  CameraAnimationType,
  CameraPosition,
  Duration,
  GeoPoint,
  Tilt,
  Zoom,
} from '@2gis/dgis-mobile-sdk-map';

export interface CameraStep {
  position: CameraPosition;
  duration: Duration;
  animationType: CameraAnimationType;
}

export type CameraPath = CameraStep[];

export interface CameraPathEntry {
  label: string;
  path: CameraPath;
}

// ── Helper to reduce boilerplate ────────────────────────────────────────────

function step(
  lat: number,
  lon: number,
  zoom: number,
  tilt: number,
  bearing: number,
  seconds: number,
): CameraStep {
  return {
    position: new CameraPosition({
      point: new GeoPoint({
        latitude: { value: lat },
        longitude: { value: lon },
      }),
      zoom: new Zoom({ value: zoom }),
      tilt: new Tilt({ value: tilt }),
      bearing: new Bearing({ value: bearing }),
    }),
    duration: Duration.ofSeconds(seconds),
    animationType: CameraAnimationType.Linear,
  };
}

